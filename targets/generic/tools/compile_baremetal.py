#!/usr/bin/env python3
"""
Bare-metal ARM64 compilation pipeline for SDC test cases.

Input:  C file generated by BareMetalDiffWrapper (uses inline asm + printf)
Output: Bare-metal ELF with _start at 0x80000, self-halting with wfi

Tool chain: aarch64-elf-gcc (homebrew) + aarch64-elf-as/ld + stub headers

Pipeline:
  1. Preprocess C to:
       - Replace printf with a stub that emits via semihosting or is ignored
       - Remove FPU/SIMD inline asm from benchmark (replaced with nop)
       - Replace return 0 with halt loop
  2. aarch64-elf-gcc -S  → assembly
  3. aarch64-elf-as      → object
  4. aarch64-elf-ld -T linker_script → ELF
"""

from __future__ import annotations

import hashlib
import re
import subprocess
import sys
from pathlib import Path
from typing import List, Optional, Tuple

# ---------------------------------------------------------------------------
# Configuration
# ---------------------------------------------------------------------------
AARCH64_ELF_GCC = "/opt/homebrew/bin/aarch64-elf-gcc"
AARCH64_ELF_AS  = "/opt/homebrew/bin/aarch64-elf-as"
AARCH64_ELF_LD  = "/opt/homebrew/bin/aarch64-elf-ld"
AARCH64_ELF_OBJCOPY = "/opt/homebrew/bin/aarch64-elf-objcopy"
AARCH64_ELF_READELF = "/opt/homebrew/bin/aarch64-elf-readelf"

STUB_DIR = Path(__file__).parent / "arm64_stubs"
LINKER_SCRIPT = Path(__file__).parent / "baremetal.ld"

# Entry point for bare-metal ELF
ENTRY_VADDR = 0x80000


