def _write_linker_script() -> None:
    """Create bare-metal linker script."""
    content = f"""\
ENTRY(_start)
MEMORY {{
    RAM (rx) : ORIGIN = 0x{ENTRY_VADDR:08x}, LENGTH = 256M
}}
SECTIONS {{
    . = 0x{ENTRY_VADDR:08x};
    .text : {{
        *(.text.startup)
        *(.text)
    }}
    .rodata : {{
        *(.rodata*)
    }}
    .data : {{
        *(.data*)
    }}
    .bss : {{
        *(.bss*)
        *(COMMON)
    }}
    /DISCARD/ : {{
        *(.comment)
        *(.note.GNU-stack)
        *(.note*)
    }}
}}
"""
    LINKER_SCRIPT.write_text(content, encoding="utf-8")


